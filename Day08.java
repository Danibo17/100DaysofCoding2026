public class Day08 {
    public static void main(String[] args) {
        // 1. Deklarasi variabel : membuat variabel yang akan digunakan
        int umur;
        String nama;

        // 2. Inisialisasi : memberikan nilai awal
        umur = 17;
        nama = "Dani";
        System.out.println("Sebelum diubah:");
        System.out.println("Nama : " + nama);
        System.out.println("Umur : " + umur);

        // 3. Update (Ubah nilai)
        umur = 18;
        nama = "Dani Ibo";
        System.out.println("\nSetelah diubah:");
        System.out.println("Nama : " + nama);
        System.out.println("Umur : " + umur);
    }
}
